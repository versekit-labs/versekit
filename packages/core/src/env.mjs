const warned = new Set();

/** An explicitly set new variable, including an empty string, takes precedence. */
export function readEnv(name, env = process.env) {
  if (env[name] !== undefined) return env[name];
  const legacy = legacyNames[name];
  const value = legacy === undefined ? undefined : env[legacy];
  if (value !== undefined && !warned.has(legacy)) {
    warned.add(legacy);
    process.stderr.write(`${legacy} 已改名为 ${name}，请更新环境变量。\n`);
  }
  return value;
}
